-- Desktop tests; the smoke target also exercises the real example games.
if has_config("build_tests") and not is_plat("android") then
    if has_config("physics_box2d") then
        target("goo_tests")
            set_kind("binary")
            set_languages("c++17")
            set_default(false)
            add_files("goo.cpp")
            add_deps("raygame")
            set_targetdir("$(builddir)/desktop/$(plat)/$(arch)/$(mode)")
        target_end()
    end
    target("campaign_tests")
        set_kind("binary")
        set_languages("c++17")
        set_default(false)
        add_files("campaigns.cpp")
        add_deps("raygame")
        set_targetdir("$(builddir)/desktop/$(plat)/$(arch)/$(mode)")
    target_end()
    if is_plat("windows", "mingw") then
        target("tts_smoke")
            set_kind("binary")
            set_languages("c++17")
            set_default(false)
            add_files("tts_smoke.cpp")
            add_deps("raygame")
            set_targetdir("$(builddir)/desktop/$(plat)/$(arch)/$(mode)")
        target_end()
    end
    target("tests")
        set_kind("binary")
        set_languages("c++17")
        set_basename("tests")
        set_default(false)
        add_files("main.cpp", "header_compat.cpp", "platform_files.cpp")
        add_deps("raygame")
        set_targetdir("$(builddir)/desktop/$(plat)/$(arch)/$(mode)")
    target_end()

    -- Requires an OpenGL-capable display.
    target("smoke")
        set_kind("binary")
        set_languages("c++17")
        set_default(false)
        add_files("smoke.cpp", "window_theme.cpp")
        add_deps("raygame", "example_assets")
        add_deps("space_shooter_assets", "bouncing_balls_assets", "neon_breakout_assets", "bullet_hell_assets")
        set_targetdir("$(builddir)/desktop/$(plat)/$(arch)/$(mode)")
    target_end()
end
