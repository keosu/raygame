#!/usr/bin/env python3
"""Builds the fighter pose sprites in assets/poses/ from full-body renders.

Usage:
    python tools/make_poses.py [--source DIR]

Sources are Ultra series wiki renders (ultra.fandom.com), downloaded as the original PNG
(append ?format=original; the CDN otherwise serves lossy WebP):

    Z Original.png, Zetto2render.png, Ultraman Z Red Damage render.png,
    Ultraman Z Original Zestium Beam pose.png, UltramanZ render.png,
    Red King G1.png, Red King Z.png, Red King Movie I.png

Every pose of one fighter is scaled so the fighter keeps one size in game: a pose is
`height * rel` pixels tall, where `rel` is its standing height relative to the idle pose.
Writes assets/poses/poses.txt with each pose's body centre (share of the width, measured
on the upper body so tails and stretched arms do not pull it) and which way it faces.
"""

import argparse
import os
import sys

import numpy as np
from PIL import Image, ImageEnhance

# key: (file, fighter height in px, rel, facing -1 left / 0 front / 1 right, options)
POSES = {
    "z_idle": ("Z_Original.png", 800, 1.0, 0, {}),
    "z_step": ("Zetto2render.png", 800, 1.0, 0, {}),
    "z_hurt": ("Ultraman_Z_Red_Damage_render.png", 800, 0.985, 0, {}),
    "z_beam": ("Ultraman_Z_Original_Zestium_Beam_pose.png", 800, 0.96, -1,
               {"contrast": 1.22, "color": 1.35, "brightness": 0.9, "match": "z_idle"}),
    "z_win": ("UltramanZ_render.png", 800, 1.0, 0, {}),
    "rk_idle": ("Red_King_G1.png", 860, 1.0, 0, {}),
    "rk_raise": ("Red_King_Z.png", 860, 1.0, -1, {}),
    "rk_roar": ("Red_King_Movie_I.png", 860, 0.93, -1, {"trim_bottom": 0.86, "match": "rk_idle"}),
}

ALPHA_FLOOR = 24


def load(source, name):
    image = Image.open(os.path.join(source, name)).convert("RGBA")
    return image


def color_match(image, reference):
    """Moves the opaque pixels' per-channel mean and spread onto the reference's."""
    a = np.asarray(image).astype(np.float32)
    r = np.asarray(reference).astype(np.float32)
    mask = a[..., 3] > 128
    ref_mask = r[..., 3] > 128
    for c in range(3):
        src, ref = a[..., c][mask], r[..., c][ref_mask]
        scale = ref.std() / max(1.0, src.std())
        a[..., c][mask] = (src - src.mean()) * scale + ref.mean()
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGBA")


def body_centre(image):
    """Alpha-weighted centre of the top 60 % of the figure, as a share of the width."""
    alpha = np.asarray(image.getchannel("A")).astype(np.float32)
    rows = int(alpha.shape[0] * 0.6)
    upper = alpha[:rows]
    xs = np.arange(alpha.shape[1], dtype=np.float32)
    weight = upper.sum()
    return float((upper.sum(axis=0) * xs).sum() / weight / alpha.shape[1]) if weight else 0.5


def build(source, file, height, rel, options, references):
    image = load(source, file)
    if "trim_bottom" in options:
        image = image.crop((0, 0, image.width, int(image.height * options["trim_bottom"])))
    image = image.crop(image.getchannel("A").point(lambda v: 255 if v > ALPHA_FLOOR else 0).getbbox())
    alpha = image.getchannel("A")
    rgb = image.convert("RGB")
    if "contrast" in options:
        rgb = ImageEnhance.Contrast(rgb).enhance(options["contrast"])
    if "color" in options:
        rgb = ImageEnhance.Color(rgb).enhance(options["color"])
    if "brightness" in options:
        rgb = ImageEnhance.Brightness(rgb).enhance(options["brightness"])
    image = rgb.convert("RGBA")
    image.putalpha(alpha)
    if options.get("match") in references:
        image = color_match(image, references[options["match"]])
    target_h = int(round(height * rel))
    target_w = max(1, int(round(image.width * target_h / image.height)))
    image = image.resize((target_w, target_h), Image.Resampling.LANCZOS)
    image.putalpha(image.getchannel("A").point(lambda v: 0 if v < ALPHA_FLOOR else v))
    return image


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default=os.path.join(here, "..", "..", "..", "build", "uq-src"))
    parser.add_argument("--out", default=os.path.join(here, "..", "assets", "poses"))
    args = parser.parse_args()
    out = os.path.normpath(args.out)
    os.makedirs(out, exist_ok=True)

    references = {}
    lines = ["# key anchor_x facing  (generated by tools/make_poses.py)"]
    for key, (file, height, rel, facing, options) in POSES.items():
        if not os.path.isfile(os.path.join(args.source, file)):
            print(f"missing {file}")
            return 1
        image = build(args.source, file, height, rel, options, references)
        references[key] = image
        image.save(os.path.join(out, key + ".png"), "PNG", optimize=True)
        anchor = body_centre(image)
        lines.append(f"{key} {anchor:.3f} {facing}")
        print(f"{key}: {image.width}x{image.height} anchor {anchor:.3f}")
    with open(os.path.join(out, "poses.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
